package app

import core.Greeting

class MainTest extends munit.FunSuite {
  test("core greeting crosses the module boundary") {
    assertEquals(Greeting.render, "hello from sbt multi-module")
  }

  test("buildinfo is generated by the plugin inside the sandbox") {
    assertEquals(app.buildinfo.BuildInfo.name, "example-sbt-multi-app")
  }

  test("core resources are on the test classpath") {
    val banner =
      scala.io.Source.fromResource("core-banner.txt").mkString.trim
    assertEquals(banner, "core-resource-ok")
  }
}
